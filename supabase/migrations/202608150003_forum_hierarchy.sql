-- Fórum canónico: categoria -> pasta -> tópico -> posts.
-- Preserva os registos de atividade existentes e mantém a atribuição de XP atual.
begin;

create table if not exists public.forum_categories (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  name text not null,
  description text not null default '',
  sort_order integer not null default 0,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.forum_sections (
  id bigint generated by default as identity primary key,
  category_id bigint not null references public.forum_categories(id) on delete restrict,
  parent_id bigint references public.forum_sections(id) on delete restrict,
  slug text not null unique,
  name text not null,
  description text not null default '',
  sort_order integer not null default 0,
  is_private boolean not null default false,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.forum_topics (
  id text primary key,
  section_id bigint not null references public.forum_sections(id) on delete restrict,
  author_id uuid not null references public.profiles(id) on delete restrict,
  title text not null check (char_length(title) between 1 and 120),
  body text not null check (char_length(body) between 1 and 5000),
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  is_private boolean not null default false,
  is_pinned boolean not null default false,
  is_locked boolean not null default false,
  view_count integer not null default 0 check (view_count >= 0),
  approved_by uuid references public.profiles(id) on delete set null,
  approved_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  last_activity_at timestamptz not null default now()
);

create table if not exists public.forum_posts (
  id text primary key,
  topic_id text not null references public.forum_topics(id) on delete cascade,
  author_id uuid not null references public.profiles(id) on delete restrict,
  body text not null check (char_length(body) between 1 and 5000),
  is_original boolean not null default false,
  is_private boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (topic_id, id)
);

create unique index if not exists forum_posts_one_original
  on public.forum_posts(topic_id) where is_original;
create index if not exists forum_topics_section_activity
  on public.forum_topics(section_id, status, is_pinned desc, last_activity_at desc);
create index if not exists forum_posts_topic_created
  on public.forum_posts(topic_id, created_at);

create table if not exists public.forum_topic_views (
  topic_id text not null references public.forum_topics(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  viewed_on date not null default current_date,
  created_at timestamptz not null default now(),
  primary key(topic_id, user_id, viewed_on)
);

