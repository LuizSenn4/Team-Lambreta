grant select on public.forum_categories,public.forum_sections,public.forum_topics,public.forum_posts to authenticated;

create or replace function public.tl_forum_create_topic_v2(
  p_section_id bigint,p_title text,p_body text
) returns jsonb language plpgsql security definer set search_path=public
as $$
declare
  v_uid uuid:=auth.uid(); v_id text; v_post_id text; v_private boolean; v_status text;
begin
  if v_uid is null then raise exception 'Login necessário'; end if;
  if char_length(trim(p_title)) not between 1 and 120 or char_length(trim(p_body)) not between 1 and 5000 then
    raise exception 'Conteúdo do tópico inválido';
  end if;
  select is_private into v_private from public.forum_sections where id=p_section_id and is_active;
  if not found then raise exception 'Pasta inválida'; end if;
  if (select count(*) from public.forum_topics where author_id=v_uid and created_at>now()-interval '1 hour')>=10 then
    raise exception 'Limite de tópicos por hora atingido';
  end if;
  v_id:='topic_'||replace(gen_random_uuid()::text,'-','');
  v_post_id:='post_'||replace(gen_random_uuid()::text,'-','');
  v_status:=case when public.tl_is_forum_moderator(v_uid) then 'approved' else 'pending' end;
  insert into public.forum_topics(id,section_id,author_id,title,body,status,is_private,approved_by,approved_at)
  values(v_id,p_section_id,v_uid,trim(p_title),trim(p_body),v_status,v_private,
         case when v_status='approved' then v_uid end,case when v_status='approved' then now() end);
  insert into public.forum_posts(id,topic_id,author_id,body,is_original,is_private)
  values(v_post_id,v_id,v_uid,trim(p_body),true,v_private);
  if v_status='approved' then perform public.tl_award_forum_xp(v_uid,'forum_topic','topic:'||v_id,20); end if;
  return jsonb_build_object('id',v_id,'post_id',v_post_id,'status',v_status);
end;
$$;

create or replace function public.tl_forum_create_post_v2(p_topic_id text,p_body text)
returns jsonb language plpgsql security definer set search_path=public
as $$
declare v_uid uuid:=auth.uid(); v_id text; v_private boolean;
begin
  if v_uid is null then raise exception 'Login necessário'; end if;
  if char_length(trim(p_body)) not between 1 and 5000 then raise exception 'Resposta inválida'; end if;
  select is_private into v_private from public.forum_topics
  where id=p_topic_id and status='approved' and not is_locked
    and (not is_private or author_id=v_uid or public.tl_is_forum_moderator(v_uid));
  if not found then raise exception 'Tópico indisponível ou fechado'; end if;
  if (select count(*) from public.forum_posts where author_id=v_uid and created_at>now()-interval '1 hour')>=50 then
    raise exception 'Limite de respostas por hora atingido';
  end if;
  v_id:='post_'||replace(gen_random_uuid()::text,'-','');
  insert into public.forum_posts(id,topic_id,author_id,body,is_private)
  values(v_id,p_topic_id,v_uid,trim(p_body),v_private);
  update public.forum_topics set updated_at=now(),last_activity_at=now() where id=p_topic_id;
  perform public.tl_award_forum_xp(v_uid,'forum_reply','reply:'||v_id,8);
  return jsonb_build_object('id',v_id,'topic_id',p_topic_id);
end;
$$;

create or replace function public.tl_forum_moderate_topic_v2(
  p_topic_id text,p_action text,p_section_id bigint default null
) returns jsonb language plpgsql security definer set search_path=public
as $$
declare v_uid uuid:=auth.uid(); v_topic public.forum_topics; v_was_approved boolean;
begin
  if not public.tl_is_forum_moderator(v_uid) then raise exception 'Sem permissão'; end if;
  select * into v_topic from public.forum_topics where id=p_topic_id for update;
  if not found then raise exception 'Tópico não encontrado'; end if;
  v_was_approved:=v_topic.status='approved';
  case lower(p_action)
    when 'approve' then
      update public.forum_topics set status='approved',approved_by=v_uid,approved_at=coalesce(approved_at,now()),updated_at=now() where id=p_topic_id;
      if not v_was_approved then perform public.tl_award_forum_xp(v_topic.author_id,'forum_topic','topic:'||p_topic_id,20); end if;
    when 'reject' then update public.forum_topics set status='rejected',updated_at=now() where id=p_topic_id;
    when 'pin' then update public.forum_topics set is_pinned=true,updated_at=now() where id=p_topic_id;
    when 'unpin' then update public.forum_topics set is_pinned=false,updated_at=now() where id=p_topic_id;
    when 'lock' then update public.forum_topics set is_locked=true,updated_at=now() where id=p_topic_id;
    when 'unlock' then update public.forum_topics set is_locked=false,updated_at=now() where id=p_topic_id;
    when 'move' then
      if not exists(select 1 from public.forum_sections where id=p_section_id and is_active) then raise exception 'Pasta inválida'; end if;
      update public.forum_topics t set section_id=p_section_id,is_private=s.is_private,updated_at=now()
      from public.forum_sections s where t.id=p_topic_id and s.id=p_section_id;
      update public.forum_posts p set is_private=t.is_private from public.forum_topics t where p.topic_id=t.id and t.id=p_topic_id;
    else raise exception 'Ação inválida';
  end case;
  return jsonb_build_object('id',p_topic_id,'action',lower(p_action));
end;
$$;

create or replace function public.tl_forum_register_view(p_topic_id text)
returns integer language plpgsql security definer set search_path=public
as $$
declare v_uid uuid:=auth.uid(); v_inserted integer;
begin
  if v_uid is null then raise exception 'Login necessário'; end if;
  if not exists(select 1 from public.forum_topics where id=p_topic_id and status='approved') then raise exception 'Tópico indisponível'; end if;
  insert into public.forum_topic_views(topic_id,user_id) values(p_topic_id,v_uid) on conflict do nothing;
  get diagnostics v_inserted=row_count;
  if v_inserted=1 then update public.forum_topics set view_count=view_count+1 where id=p_topic_id; end if;
  return (select view_count from public.forum_topics where id=p_topic_id);
end;
$$;

revoke all on function public.tl_forum_create_topic_v2(bigint,text,text) from public;
revoke all on function public.tl_forum_create_post_v2(text,text) from public;
revoke all on function public.tl_forum_moderate_topic_v2(text,text,bigint) from public;
revoke all on function public.tl_forum_register_view(text) from public;
grant execute on function public.tl_forum_create_topic_v2(bigint,text,text) to authenticated;
grant execute on function public.tl_forum_create_post_v2(text,text) to authenticated;
grant execute on function public.tl_forum_moderate_topic_v2(text,text,bigint) to authenticated;
grant execute on function public.tl_forum_register_view(text) to authenticated;

commit;
