-- Promove os tópicos que já sustentavam o XP para a estrutura canónica.
insert into public.forum_topics(
  id,section_id,author_id,title,body,status,is_private,created_at,updated_at,last_activity_at
)
select t.topic_key,s.id,t.user_id,t.title,t.body,
       case when t.is_approved then 'approved' else 'pending' end,
       t.is_private,t.created_at,t.created_at,
       coalesce((select max(r.created_at) from public.forum_activity_replies r where r.topic_key=t.topic_key),t.created_at)
from public.forum_activity_topics t
join public.forum_sections s on s.slug=(case t.category
  when 'suporte' then 'site' when 'loja' then 'loja' when 'sugestoes' then 'sugestoes'
  when 'duvidas' then 'duvidas' when 'ajuda' then 'duvidas' when 'candidaturas' then 'candidaturas'
  when 'eventos' then 'eventos' when 'fortnite' then 'fortnite' when 'denuncias' then 'denuncias'
  else 'geral' end)
on conflict(id) do nothing;

insert into public.forum_posts(id,topic_id,author_id,body,is_original,is_private,created_at,updated_at)
select 'original_'||t.topic_key,t.topic_key,t.user_id,t.body,true,t.is_private,t.created_at,t.created_at
from public.forum_activity_topics t
join public.forum_topics ft on ft.id=t.topic_key
on conflict(id) do nothing;

insert into public.forum_posts(id,topic_id,author_id,body,is_original,is_private,created_at,updated_at)
select r.reply_key,r.topic_key,r.user_id,r.body,false,r.is_private,r.created_at,r.created_at
from public.forum_activity_replies r
join public.forum_topics ft on ft.id=r.topic_key
on conflict(id) do nothing;

create or replace function public.tl_is_forum_moderator(p_user_id uuid default auth.uid())
returns boolean language sql stable security definer set search_path=public
as $$
  select exists(
    select 1 from public.profiles p
    where p.id=p_user_id and lower(p.role::text) in ('master','dev','admin','staff','moderator','moderador','boss')
  );
$$;
revoke all on function public.tl_is_forum_moderator(uuid) from public;
grant execute on function public.tl_is_forum_moderator(uuid) to authenticated;

alter table public.forum_categories enable row level security;
alter table public.forum_sections enable row level security;
alter table public.forum_topics enable row level security;
alter table public.forum_posts enable row level security;
alter table public.forum_topic_views enable row level security;

drop policy if exists forum_categories_members_read on public.forum_categories;
create policy forum_categories_members_read on public.forum_categories for select to authenticated
using (is_active);
drop policy if exists forum_sections_members_read on public.forum_sections;
create policy forum_sections_members_read on public.forum_sections for select to authenticated
using (is_active);
drop policy if exists forum_topics_members_read on public.forum_topics;
create policy forum_topics_members_read on public.forum_topics for select to authenticated
using (
  (status='approved' or author_id=auth.uid() or public.tl_is_forum_moderator())
  and (not is_private or author_id=auth.uid() or public.tl_is_forum_moderator())
);
drop policy if exists forum_posts_members_read on public.forum_posts;
create policy forum_posts_members_read on public.forum_posts for select to authenticated
using (
  exists(select 1 from public.forum_topics t where t.id=topic_id)
  and (not is_private or author_id=auth.uid() or public.tl_is_forum_moderator())
);

revoke all on public.forum_categories,public.forum_sections,public.forum_topics,public.forum_posts,public.forum_topic_views from anon;
